#!/usr/bin/env python
"""Turns the output of photos_reference.py (one run per TZ) into the expected values embedded in
tests/PhotosServiceTest.php (between the `BEGIN EXPECTED` / `END EXPECTED` markers).

    TZ=Etc/UTC       .venv/bin/python -I var/photos_reference.py > utc.json
    TZ=Europe/Paris  .venv/bin/python -I var/photos_reference.py > paris.json
    python3 var/gen_photos_expected.py utc.json paris.json ~/Sites/icloudpd/tests/PhotosServiceTest.php
"""

import hashlib
import json
import re
import sys

SHORT = {
    "AssetVersionSize.ORIGINAL": "o",
    "AssetVersionSize.ADJUSTED": "j",
    "AssetVersionSize.ALTERNATIVE": "a",
    "AssetVersionSize.MEDIUM": "m",
    "AssetVersionSize.THUMB": "t",
    "LivePhotoVersionSize.ORIGINAL": "O",
    "LivePhotoVersionSize.MEDIUM": "M",
    "LivePhotoVersionSize.THUMB": "T",
}
# scenarios whose 100 rows are all listed, the others only keep the 3 first rows and a hash of all of them
FULL_ROWS = {"listing_photos/photos", "listing_videos/photos", "download_live_photos/photos"}
# scenarios with the 5 first photos in full, the others have 3
RAW = {"listing_photos_raw/photos", "listing_photos_raw_alt/photos", "listing_photos_raw_alt_adj/photos"}
FULL_5 = FULL_ROWS | RAW
# `versions_with_raw_policy` for the 3 policies is only kept for those
WITH_RAW = {"listing_photos/photos", "download_live_photos/photos"} | RAW

leaves = 0


def sha1(s: str) -> str:
    return hashlib.sha1(s.encode("utf-8")).hexdigest()


def canon(o) -> str:
    return json.dumps(o, sort_keys=True, separators=(",", ":"))


def is_err(v) -> bool:
    return isinstance(v, dict) and "$error" in v


def row(c) -> str:
    id_, filename, item_type, created, keys = c
    f = "!" + filename["$error"] if is_err(filename) else filename
    t = "!" + item_type["$error"] if is_err(item_type) else (item_type or "-")
    d = "!" + created["$error"] if is_err(created) else created["ts"]
    k = "!" + keys["$error"] if is_err(keys) else ",".join(SHORT[x] for x in keys)
    return "|".join([id_, f, t, d, k])


def prune_info(i, scenario, first, paris):
    i = dict(i)
    if isinstance(i["versions"], list):
        vs = []
        for v in i["versions"]:
            v = dict(v)
            v["url_sha1"] = sha1(v.pop("url"))
            vs.append(v)
        i["versions"] = vs
    if scenario in WITH_RAW:
        i["raw"] = {
            k: ([[a, b, sha1(c), d] for a, b, c, d in v] if isinstance(v, list) else v)
            for k, v in i["raw"].items()
        }
    else:
        del i["raw"]
    i["created_paris"] = paris["created"]
    return i


def prune_request(r):
    r = dict(r)
    c = canon(r["body"])
    if r["body"] is not None and len(c) > 400:
        r["body"] = None
        r["body_sha1"] = sha1(c)
    return r


def main() -> None:
    utc = json.load(open(sys.argv[1]))
    paris = json.load(open(sys.argv[2]))
    out = {}
    for key, v in utc.items():
        res = v["result"]
        if key.endswith("/photos") or key.endswith("/shared") or key.endswith("/deleted"):
            n_full = 5 if key in FULL_5 else 2
            pf = paris[key]["result"]["full"]
            full = []
            for idx, i in enumerate(res["full"][:n_full]):
                full.append(prune_info(i, key, idx == 0, pf[idx]))
            rows = [row(c) for c in res["compact"]]
            res = dict(res)
            res["full"] = full
            del res["compact"]
            if key in FULL_ROWS:
                res["rows"] = rows
            else:
                res["rows_head"] = rows[:3]
                res["rows_sha1"] = sha1("\n".join(rows))
        out[key] = {"requests": [prune_request(r) for r in v["requests"]], "result": res}
    # the literal download URLs of the first photo of listing_photos
    first = utc["listing_photos/photos"]["result"]["full"][0]
    out["listing_photos/photos"]["result"]["urls_literal"] = {v["key"]: v["url"] for v in first["versions"]}
    text = json.dumps(out, ensure_ascii=False, separators=(",", ":"))

    def count(o):
        if isinstance(o, dict):
            return sum(count(x) for x in o.values())
        if isinstance(o, list):
            return sum(count(x) for x in o)
        return 1

    sys.stderr.write(f"{len(text)} bytes, {count(out)} leaf values\n")
    test = open(sys.argv[3]).read()
    block = "    // BEGIN EXPECTED (generated by var/gen_photos_expected.py)\n    private const EXPECTED = <<<'JSON'\n" + text + "\nJSON;\n    // END EXPECTED\n"
    test = re.sub(r"    // BEGIN EXPECTED.*?// END EXPECTED\n", lambda m: block, test, flags=re.S)
    open(sys.argv[3], "w").write(test)


main()
